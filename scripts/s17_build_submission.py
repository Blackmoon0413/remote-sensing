#!/usr/bin/env python3
"""S17: build the submission package from the current manuscript and results.

D:/rsicc_v2/submission/
  1_manuscript/       main.pdf, latex_source.zip (single flattened main.tex + bib/bbl + Definitions + figs)
  2_cover_letter/     (written by hand, kept)
  3_release/          rsicc-change-state-audit/ (code + results, sanitised) and its zip;
                      features.zip (frozen-encoder evidence features), change3d_checkpoints.zip (GitHub release assets)
  4_checklist/        (written by hand, kept)
Re-run after any change to the manuscript or results. Directories 2 and 4 are never touched.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

V2 = Path("D:/rsicc_v2")
MS = V2 / "manuscript"
SUB = V2 / "submission"
FIGS = ["fig_workflow.pdf", "fig_workflow.tex", "test_000002_A.png", "test_000002_B.png",
        "fig_flag_recovery.pdf", "fig_fp_fn.pdf", "fig_cases.pdf", "fig_cases.tex",
        "fig_error_profile.pdf", "fig_evidence.pdf", "fig_tradeoff.pdf", "fig_cost.pdf"]
FIG_DIRS = ["cases", "maps"]  # image pairs and patch-change maps used by fig_cases.tex / fig_workflow.tex
REPO = "rsicc-change-state-audit"


def zipdir(src: Path, dst: Path, arc_root: str | None = None) -> None:
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(src.rglob("*")):
            if p.is_file():
                z.write(p, (Path(arc_root) / p.relative_to(src)) if arc_root else p.relative_to(src))


def run(cmd, cwd):
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, errors="replace")


def build_latex() -> None:
    out = SUB / "1_manuscript"; src = out / "latex_source"
    if src.exists():
        shutil.rmtree(src)
    (src / "figs").mkdir(parents=True)
    tex = (MS / "main.tex").read_text(encoding="utf-8")
    # flatten generated tables into the single .tex file MDPI receives
    def inline(m):
        body = (MS / m.group(1)).read_text(encoding="utf-8").rstrip("\n")
        return f"% --- {m.group(1)} (generated by scripts/s16_tables.py) ---\n{body}"
    tex, n = re.subn(r"\\inputtable\{([^}]+)\}", inline, tex)
    tex = tex.replace("% \\input inside tabular breaks \\bottomrule (Misplaced \\noalign); use the TeX primitive instead.\n"
                      "\\makeatletter\n\\newcommand{\\inputtable}[1]{\\@@input #1 }\n\\makeatother\n", "")
    (src / "main.tex").write_text(tex, encoding="utf-8", newline="\n")
    shutil.copy(MS / "references.bib", src)
    shutil.copytree(MS / "Definitions", src / "Definitions",
                    ignore=shutil.ignore_patterns("*-eps-converted-to.pdf"))
    for f in FIGS:
        shutil.copy(MS / "figs" / f, src / "figs" / f)
    for d in FIG_DIRS:
        shutil.copytree(MS / "figs" / d, src / "figs" / d)
    for c in (["pdflatex", "-interaction=nonstopmode", "main.tex"], ["bibtex", "main"],
              ["pdflatex", "-interaction=nonstopmode", "main.tex"], ["pdflatex", "-interaction=nonstopmode", "main.tex"]):
        run(c, src)
    log = (src / "main.log").read_text(encoding="utf-8", errors="replace")
    errs = [l for l in log.splitlines() if l.startswith("! ")]
    pages = re.search(r"Output written on main\.pdf \((\d+) pages", log)
    print(f"[latex] inlined {n} tables; errors {len(errs)}; overfull {log.count('Overfull')}; "
          f"pages {pages.group(1) if pages else '?'}")
    if errs:
        sys.exit("LaTeX errors: " + "; ".join(errs[:3]))
    try:
        shutil.copy(src / "main.pdf", out / "main.pdf")
    except PermissionError:  # the old PDF is open in a viewer (Windows locks it)
        shutil.copy(src / "main.pdf", out / "main_latest.pdf")
        print("[latex] WARNING: 1_manuscript/main.pdf is open in another program; wrote main_latest.pdf instead. "
              "Close the viewer and re-run to update main.pdf.")
    keep = {"main.tex", "references.bib", "main.bbl", "Definitions", "figs"}
    for p in list(src.iterdir()):
        if p.name not in keep:
            p.unlink() if p.is_file() else shutil.rmtree(p)
    for p in (src / "Definitions").glob("*-eps-converted-to.pdf"):
        p.unlink()
    zipdir(src, out / "latex_source.zip")
    shutil.rmtree(src)


def build_release() -> None:
    rel = SUB / "3_release"; repo = rel / REPO
    if repo.exists():
        shutil.rmtree(repo)
    (repo / "scripts").mkdir(parents=True)
    for p in sorted((V2 / "scripts").iterdir()):
        if p.suffix in (".py", ".sh"):
            txt = p.read_text(encoding="utf-8")
            # no personal paths in the public copy
            txt = re.sub(r"PYS=/c/Users/[^ \n]+python\.exe", 'PYS="${PYS:-python}"', txt)
            txt = re.sub(r"(?i)[a-z]?:?/(?:c/)?Users/[^ \"'\n}]+python\.exe", "python", txt)
            if p.name != Path(__file__).name and re.search(r"(?i)/Users/|newprojectimage", txt):
                sys.exit(f"personal path left in {p.name}")
            (repo / "scripts" / p.name).write_text(txt, encoding="utf-8", newline="\n")
    shutil.copytree(V2 / "patches", repo / "patches")
    res = repo / "results"
    for d in sorted((V2 / "outputs").iterdir()):
        if d.is_dir() and d.name not in ("features", "audit", "figs", "feasibility"):
            for split in ("val", "test", "train"):
                f = d / split / "predictions.json"
                if f.exists():
                    (res / "predictions" / d.name).mkdir(parents=True, exist_ok=True)
                    shutil.copy(f, res / "predictions" / d.name / f"{split}.json")
            for extra in ("best_epoch.json",):
                if (d / extra).exists():
                    shutil.copy(d / extra, res / "predictions" / d.name / extra)
            for split in ("test",):
                f = d / split / "scores_repo.json"
                if f.exists():
                    shutil.copy(f, res / "predictions" / d.name / "test_scores_own_code.json")
    shutil.copytree(V2 / "outputs" / "audit", res / "audit")
    # original-prompt VLM audits (Section 5.9) and per-sample evidence/decisions (s23) for every audit file
    shutil.copytree(V2 / "outputs" / "audit_origprompt", res / "audit_origprompt")
    shutil.copytree(V2 / "outputs" / "audit_per_sample", res / "audit_per_sample")
    if (V2 / "outputs" / "feasibility").exists():
        shutil.copytree(V2 / "outputs" / "feasibility", res / "feasibility")
    for f in ("main_results.json", "summary.md", "reproduction_report.json", "knn_change_state.json", "sanity.json"):
        if (V2 / "outputs" / f).exists():
            shutil.copy(V2 / "outputs" / f, res / f)
    shutil.copy(V2 / "outputs" / "prompt_test" / "summary.json", res / "prompt_test_summary.json")
    shutil.copytree(V2 / "outputs" / "figs", res / "figs")
    # labels only (pair name, split, change flag); the reference captions belong to the datasets and are not redistributed
    (res / "labels").mkdir(exist_ok=True)
    for ds in ("levir_cc", "dubai_cc"):
        refs = json.loads((V2 / "data" / "processed" / f"refs_{ds}.json").read_text(encoding="utf-8"))
        lab = {split: [{"name": r["name"], "changeflag": r["changeflag"]} for r in rows] for split, rows in refs.items()}
        (res / "labels" / f"labels_{ds}.json").write_text(json.dumps(lab, indent=0), encoding="utf-8")
    shutil.copy(V2 / "submission" / "release_README.md", repo / "README.md")
    shutil.copy(V2 / "submission" / "release_requirements.txt", repo / "requirements.txt")
    zipdir(repo, rel / f"{REPO}.zip", REPO)
    # large artefacts kept locally only (features can be regenerated with s7; checkpoints on request)
    zf = rel / "features.zip"
    if not zf.exists():
        zipdir(V2 / "outputs" / "features", zf, "features")
    ck = rel / "change3d_checkpoints.zip"
    if not ck.exists():
        best = [json.loads((V2 / "outputs" / f"change3d_{d}" / "best_epoch.json").read_text())["checkpoint"]
                for d in ("levir", "dubai")]
        with zipfile.ZipFile(ck, "w", zipfile.ZIP_STORED) as z:
            for b in best:
                z.write(b, f"change3d_checkpoints/{Path(b).parent.name}/{Path(b).name}")
    size = lambda p: f"{p.stat().st_size / 2**20:.1f} MB"  # noqa: E731
    print(f"[release] {REPO}.zip {size(rel / f'{REPO}.zip')}; features {size(zf)}; checkpoints {size(ck)}")


if __name__ == "__main__":
    for d in ("1_manuscript", "2_cover_letter", "3_release", "4_checklist"):
        (SUB / d).mkdir(parents=True, exist_ok=True)
    build_latex()
    build_release()
